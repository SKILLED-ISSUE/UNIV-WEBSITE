          The Institution plans and implements an extension program that is need and client-based. 
          This program should have a budgetary support and other resource allocation. The faculty 
          members may serve as experts, consultants, organizers, facilitators, coordinators, service providers, 
          and change agents in the community as forms of extension and community involvement.
        <br></br>
